"""Render the load balancer's config from the live set of backends.

The controller writes this to the config directory it shares with nginx, then
asks nginx to reload. Pure string building, so it is unit-tested directly.
"""
from __future__ import annotations

from collections.abc import Iterable


def render_nginx_conf(backends: Iterable[str], port: int = 8080) -> str:
    """Build an nginx server + upstream block for the given backend hosts.

    With no backends the server answers 503, so nginx always has a valid
    config to load.
    """
    backends = list(backends)
    header = (
        "# Generated by the controller. Rewritten and reloaded live as the\n"
        "# fleet changes; do not edit by hand.\n\n"
    )

    if not backends:
        return header + (
            "server {\n"
            "    listen 80;\n"
            "    location / { return 503 \"no backends\\n\"; }\n"
            "}\n"
        )

    lines = ["upstream backend_servers {"]
    for host in backends:
        lines.append(f"    server {host}:{port} max_fails=3 fail_timeout=5s;")
    lines.append("}")
    upstream = "\n".join(lines)

    server = (
        "\n\nserver {\n"
        "    listen 80;\n\n"
        "    location / {\n"
        "        proxy_pass http://backend_servers;\n"
        "        proxy_connect_timeout 2s;\n"
        "        proxy_read_timeout 15s;\n"
        "        proxy_next_upstream error timeout http_502 http_503;\n"
        "        add_header X-Backend $upstream_addr always;\n"
        "    }\n"
        "}\n"
    )
    return header + upstream + server
